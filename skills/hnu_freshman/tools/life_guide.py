    def _guide(self, query: str) -> str:
        query = query.strip()
        if not query:
            return "你想了解校园生活的哪方面？比如食堂、宿舍、快递、图书馆、选课等。"

        # 关键词匹配
        for keyword, answer in self._faq.items():
            if keyword in query or query in keyword:
                return answer

        # 模糊匹配
        for keyword, answer in self._faq.items():
            if any(c in query for c in keyword):
                return answer

        all_topics = "、".join(self._faq.keys())
        return (
            f"我暂时没有找到关于'{query}'的具体信息。"
            f"我可以帮你解答以下方面的问题：{all_topics}。"
            f"请告诉我更具体的关键词。"
        )
